CREATE TABLE detection_batches (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    model_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    model_snapshot JSON NOT NULL,
    request_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
    request_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    image_count TINYINT UNSIGNED NOT NULL,
    error_code VARCHAR(64) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    completed_at DATETIME(6) NULL,
    CONSTRAINT uk_batch_request UNIQUE (user_id, request_key),
    CONSTRAINT fk_batch_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_batch_model FOREIGN KEY (model_id) REFERENCES model_versions(id),
    CONSTRAINT ck_batch_status CHECK (status IN ('pending', 'running', 'succeeded', 'failed')),
    CONSTRAINT ck_batch_count CHECK (image_count BETWEEN 1 AND 20),
    INDEX idx_batches_user_created (user_id, created_at, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE detection_records (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    model_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    batch_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    request_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
    batch_item_index TINYINT UNSIGNED NOT NULL DEFAULT 0,
    request_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
    original_storage_key VARCHAR(512) NOT NULL,
    mask_storage_key VARCHAR(512) NOT NULL,
    overlay_storage_key VARCHAR(512) NOT NULL,
    channel_mask_keys JSON NOT NULL,
    original_width INT UNSIGNED NOT NULL,
    original_height INT UNSIGNED NOT NULL,
    model_width INT UNSIGNED NOT NULL DEFAULT 1600,
    model_height INT UNSIGNED NOT NULL DEFAULT 256,
    total_pixels BIGINT UNSIGNED NOT NULL,
    defect_pixels BIGINT UNSIGNED NOT NULL,
    defect_count INT UNSIGNED NOT NULL,
    inference_time_ms DOUBLE NOT NULL,
    model_name_snapshot VARCHAR(100) NOT NULL,
    model_version_snapshot VARCHAR(50) NOT NULL,
    inference_config_snapshot JSON NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT uk_record_request_item UNIQUE (user_id, request_key, batch_item_index),
    CONSTRAINT fk_record_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_record_model FOREIGN KEY (model_id) REFERENCES model_versions(id),
    CONSTRAINT fk_record_batch FOREIGN KEY (batch_id) REFERENCES detection_batches(id),
    CONSTRAINT ck_record_dimensions CHECK (original_width > 0 AND original_height > 0 AND model_width > 0 AND model_height > 0),
    CONSTRAINT ck_record_total_pixels CHECK (total_pixels = original_width * original_height),
    CONSTRAINT ck_record_defect_pixels CHECK (defect_pixels <= total_pixels),
    CONSTRAINT ck_record_inference_time CHECK (inference_time_ms >= 0),
    CONSTRAINT ck_record_batch_index CHECK (batch_item_index BETWEEN 0 AND 19),
    INDEX idx_records_user_created (user_id, created_at, id),
    INDEX idx_records_created (created_at, id),
    INDEX idx_records_model (model_id),
    INDEX idx_records_batch (batch_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE detection_class_stats (
    record_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    class_index TINYINT UNSIGNED NOT NULL,
    region_count INT UNSIGNED NOT NULL,
    pixel_count BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (record_id, class_index),
    CONSTRAINT fk_class_record FOREIGN KEY (record_id) REFERENCES detection_records(id),
    CONSTRAINT ck_class_index CHECK (class_index BETWEEN 1 AND 4),
    INDEX idx_class_index (class_index)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE operation_logs (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    user_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    action VARCHAR(64) NOT NULL,
    target_id VARCHAR(64) NULL,
    status VARCHAR(16) NOT NULL,
    details JSON NULL,
    request_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    ip_address VARCHAR(45) NULL,
    user_agent VARCHAR(512) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT fk_log_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT ck_log_status CHECK (status IN ('success', 'failure')),
    INDEX idx_logs_user_created (user_id, created_at, id),
    INDEX idx_logs_action_created (action, created_at, id),
    INDEX idx_logs_created (created_at, id),
    INDEX idx_logs_request (request_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
